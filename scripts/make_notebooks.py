def render(nb: dict) -> str:
    return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"


def main() -> None:
    for path, nb in build().items():
        (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
        (ROOT / path).write_text(render(nb))
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
